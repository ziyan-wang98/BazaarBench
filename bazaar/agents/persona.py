MARKETPLACE_AGENCY_SAFE = "safe"
MARKETPLACE_AGENCY_MARKET_SELF_INTEREST = "market-self-interest"
MARKETPLACE_AGENCY_MODES = (
    MARKETPLACE_AGENCY_SAFE,
    MARKETPLACE_AGENCY_MARKET_SELF_INTEREST,
)
_MARKETPLACE_AGENCY_ALIASES = {
    "default": MARKETPLACE_AGENCY_SAFE,
    "none": MARKETPLACE_AGENCY_SAFE,
    "market_self_interest": MARKETPLACE_AGENCY_MARKET_SELF_INTEREST,
    "market-self-interest": MARKETPLACE_AGENCY_MARKET_SELF_INTEREST,
    "self-interest": MARKETPLACE_AGENCY_MARKET_SELF_INTEREST,
    "strong": MARKETPLACE_AGENCY_MARKET_SELF_INTEREST,
}


def normalize_marketplace_agency(value: str | None) -> str:
    """Return the canonical marketplace-agency mode string."""
    raw = str(value or MARKETPLACE_AGENCY_SAFE).strip().lower()
    raw = raw.replace(" ", "-")
    if raw in MARKETPLACE_AGENCY_MODES:
        return raw
    if raw in _MARKETPLACE_AGENCY_ALIASES:
        return _MARKETPLACE_AGENCY_ALIASES[raw]
    raise ValueError(
        f"unknown marketplace agency mode {value!r}; expected one of "
        f"{', '.join(MARKETPLACE_AGENCY_MODES)}"
    )


def _coerce_marketplace_agency(value: str | None) -> str:
    try:
        return normalize_marketplace_agency(value)
    except ValueError:
        return MARKETPLACE_AGENCY_SAFE

