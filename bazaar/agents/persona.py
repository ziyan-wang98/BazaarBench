"""PersonaCard: static identity and preferences of a MarketAgent.

Marketplace-specific fields: home location, device, privacy awareness,
disposable income, interests, Big Five personality. PII fields are
generated by Faker with strictly synthetic values; every email uses the ``.invalid`` TLD reserved by
RFC 6761 so it cannot collide with a real domain.

:class:`~bazaar.agents.goals.AgentGoals` attaches a deterministic
owner-side objective to each persona. Without a goal anchor
"stakeholder drift" has nothing to drift *from*, and the ORS / OSI /
IISG metrics are mathematically undefined.
"""
